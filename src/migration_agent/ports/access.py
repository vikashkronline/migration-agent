"""Typed security ports; adapters cannot manufacture authorization decisions."""

from contextlib import AbstractContextManager
from typing import Protocol

from migration_agent.domain.access import (
    AccessDecision,
    AccessPolicy,
    AccessProposal,
    AccessRevision,
    ProjectAccessBinding,
)


class AccessStorePort(Protocol):
    binding: ProjectAccessBinding

    def read(self) -> AccessPolicy: ...
    def activate(self, revision: AccessRevision) -> None: ...
    def save_proposal(self, proposal: AccessProposal) -> None: ...
    def proposal(self, proposal_id: str) -> AccessProposal: ...
    def locator(self, digest: str) -> str: ...
    def fence(self) -> AbstractContextManager[None]: ...
    def recover(self) -> None: ...
    def is_active_revision(self, revision: AccessRevision) -> bool: ...


class PublicSignaturePort(Protocol):
    def fingerprint(self, public_key: str) -> str: ...
    def verify(self, public_key: str, digest: str, signature: str) -> bool: ...
    def sign(self, public_key: str, digest: str) -> str: ...


class AuthorizationPort(Protocol):
    def require(self, capability: str, expected_digest: str | None = None) -> AccessDecision: ...
    def require_signature(self, capability: str, fingerprint: str | None) -> None: ...
    def fence(self, capability: str) -> AbstractContextManager[None]: ...
