def cloak_prompt_string(prompt: str, key_byte: int = 0x5A) -> str:
    """XOR mask and base64 encode sensitive prompt strings to deter casual string extraction."""
    raw_bytes = prompt.encode("utf-8")
    masked = bytes([b ^ key_byte for b in raw_bytes])
    return base64.b64encode(masked).decode("utf-8")


def decloak_prompt_string(cloaked: str, key_byte: int = 0x5A) -> str:
    """Decode and unmask a cloaked prompt string at runtime."""
    masked = base64.b64decode(cloaked.encode("utf-8"))
    raw_bytes = bytes([b ^ key_byte for b in masked])
    return raw_bytes.decode("utf-8")


def get_binary_packaging_spec(package_root: Path, binary_name: str = "agent") -> dict[str, Any]:
    """Return the PyInstaller bundling configuration for Migration Agent."""
    static_ui_dir = package_root / "src" / "migration_agent" / "ui" / "static"
    spec = BinaryPackagingSpec(
        canonical_name="agent",
        binary_name=binary_name,
        aliases=["migration-agent"] if binary_name == "agent" else ["agent"],
        data_files=[
            (str(static_ui_dir), "migration_agent/ui/static"),
        ],
    )
    return {
        "entry_point": spec.entry_point,
        "canonical_name": spec.canonical_name,
        "binary_name": spec.binary_name,
        "aliases": list(spec.aliases),
        "hidden_imports": list(spec.hidden_imports),
        "data_files": list(spec.data_files),
        "enable_lto": spec.enable_lto,
        "strip_binaries": spec.strip_binaries,
        "onefile": spec.onefile,
        "console": spec.console,
        "output_dir": spec.output_dir,
    }


def generate_pyinstaller_spec(
    package_root: Path,
    binary_name: str = "agent",
    aliases: list[str] | None = None,
) -> str:
    """Generate a deterministic PyInstaller .spec file content string."""
    spec_data = get_binary_packaging_spec(package_root, binary_name=binary_name)
    resolved_aliases = aliases if aliases is not None else spec_data["aliases"]
    hidden_imports_str = repr(spec_data["hidden_imports"])
    data_files_str = repr(spec_data["data_files"])

    return f"""# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by migration_agent.packaging.build_binary
# Canonical binary: {binary_name}, Aliases: {resolved_aliases}

block_cipher = None

a = Analysis(
    ['{spec_data["entry_point"]}'],
    pathex=['{package_root}'],
    binaries=[],
    datas={data_files_str},
    hiddenimports={hidden_imports_str},
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name='{binary_name}',
    debug=False,
    bootloader_ignore_signals=False,
    strip={spec_data["strip_binaries"]},
    upx=True,
    upx_exclude=[],
    runtime_tmpdir=None,
    console={spec_data["console"]},
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
"""


def write_pyinstaller_spec_file(
    package_root: Path,
    output_file: Path | None = None,
    binary_name: str = "agent",
) -> Path:
    """Write the deterministic PyInstaller .spec file to disk and return its path."""
    content = generate_pyinstaller_spec(package_root, binary_name=binary_name)
    target = output_file if output_file is not None else package_root / f"{binary_name}.spec"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return target


def create_binary_aliases(primary_binary: Path, aliases: list[str]) -> list[Path]:
    """Create hardlinks, symlinks, or file copies for binary aliases in the same directory."""
    created: list[Path] = []
    if not primary_binary.is_file():
        raise FileNotFoundError(f"Primary binary not found: {primary_binary}")

    parent = primary_binary.parent
    extension = primary_binary.suffix  # e.g. .exe on Windows

    for alias in aliases:
        alias_name = f"{alias}{extension}" if extension and not alias.endswith(extension) else alias
        alias_path = parent / alias_name
        if alias_path.resolve() == primary_binary.resolve():
            continue

        # Remove existing alias target if present
        if alias_path.exists():
            alias_path.unlink()

        try:
            # Try creating a hard link first (preserves disk space)
            os.link(primary_binary, alias_path)
        except OSError:
            # Fall back to file copy if linking is unsupported or cross-filesystem
            shutil.copy2(primary_binary, alias_path)

        created.append(alias_path)
    return created


def verify_binary_integrity(
    binary_path: Path,
    expected_sha256: str | None = None,
) -> dict[str, Any]:
    """Verify that a binary exists, is non-empty, matches executable format, and check SHA-256."""
    if not binary_path.is_file():
        return {
            "valid": False,
            "path": str(binary_path),
            "reason": f"File does not exist: {binary_path}",
        }

    size = binary_path.stat().st_size
    if size == 0:
        return {
            "valid": False,
            "path": str(binary_path),
            "reason": "Binary file is 0 bytes.",
        }

    # Inspect executable magic header
    header = binary_path.read_bytes()[:4]
    is_pe = header.startswith(b"MZ")
    is_elf = header.startswith(b"\x7fELF")
    macho_magics = (
        b"\xfe\xed\xfa\xce",
        b"\xce\xfa\xed\xfe",
        b"\xfe\xed\xfa\xcf",
        b"\xcf\xfa\xed\xfe",
        b"\xca\xfe\xba\xbe",
    )
    is_macho = header in macho_magics
    is_executable_format = is_pe or is_elf or is_macho

    hasher = hashlib.sha256()
    with binary_path.open("rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    actual_sha256 = hasher.hexdigest()

    if expected_sha256 is not None and actual_sha256.lower() != expected_sha256.lower():
        return {
            "valid": False,
            "path": str(binary_path),
            "size_bytes": size,
            "sha256": actual_sha256,
            "reason": f"SHA-256 mismatch (expected {expected_sha256}, got {actual_sha256})",
        }

    return {
        "valid": True,
        "path": str(binary_path),
        "size_bytes": size,
        "sha256": actual_sha256,
        "is_executable_format": is_executable_format,
        "format": "PE" if is_pe else ("ELF" if is_elf else ("Mach-O" if is_macho else "unknown")),
    }
